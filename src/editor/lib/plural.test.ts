import { describe, expect, it } from "vitest";
import { records } from "./plural";

describe("plural", () => {
	it("склоняет по последним цифрам", () => {
		expect(
			[0, 1, 2, 4, 5, 11, 12, 14, 21, 22, 25, 101, 111].map(records),
		).toEqual([
			"0 записей",
			"1 запись",
			"2 записи",
			"4 записи",
			"5 записей",
			"11 записей",
			"12 записей",
			"14 записей",
			"21 запись",
			"22 записи",
			"25 записей",
			"101 запись",
			"111 записей",
		]);
	});
});
